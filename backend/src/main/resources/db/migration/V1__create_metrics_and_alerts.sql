CREATE TABLE traffic_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(80) NOT NULL,
    request_count BIGINT NOT NULL CHECK (request_count >= 0),
    error_count BIGINT NOT NULL CHECK (error_count >= 0 AND error_count <= request_count),
    p95_latency_ms BIGINT NOT NULL CHECK (p95_latency_ms >= 0),
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_traffic_metrics_collected_at ON traffic_metrics (collected_at DESC);
CREATE INDEX idx_traffic_metrics_service_time ON traffic_metrics (service_name, collected_at DESC);

CREATE TABLE alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_id BIGINT NOT NULL REFERENCES traffic_metrics(id),
    service_name VARCHAR(80) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    rule_code VARCHAR(40) NOT NULL,
    message VARCHAR(240) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_alerts_status_created_at ON alerts (status, created_at DESC);

