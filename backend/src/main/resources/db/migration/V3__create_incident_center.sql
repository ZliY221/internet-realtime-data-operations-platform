CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(80) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    status VARCHAR(20) NOT NULL,
    title VARCHAR(160) NOT NULL,
    owner VARCHAR(80),
    alert_count INTEGER NOT NULL CHECK (alert_count > 0),
    first_alert_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_alert_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_incidents_status_updated_at ON incidents (status, updated_at DESC);
CREATE INDEX idx_incidents_service_status ON incidents (service_name, status);

ALTER TABLE alerts ADD COLUMN incident_id BIGINT REFERENCES incidents(id);
CREATE INDEX idx_alerts_incident_id ON alerts (incident_id);
